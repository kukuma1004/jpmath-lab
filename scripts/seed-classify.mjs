function hit(text, words) {
  return words.some((w) => text.includes(w));
}

export function classifySeed(seed) {
  // 개념만으로는 모자란다. 뱅크 씨앗은 개념 칸에 제목이 들어 있는 경우가
  // 있어서 제목과 질문까지 함께 본다.
  const evidence = [
    (seed.concepts || []).join(' '),
    seed.title,
    seed.question,
    seed.baseTopic
  ].filter(Boolean).join(' ');

  const stage = hit(evidence, HIGH_ONLY)
    ? 'high'
    : hit(evidence, MIDDLE_OK) ? 'middle' : 'high';

  const surface = [
    seed.title, seed.question, seed.baseTopic, seed.phenomenon, seed.situation,
    (seed.domain || []).join(' ')
  ].filter(Boolean).join(' ');
  const track = hit(surface, REAL_WORLD) ? 'connected' : 'internal';

  return { stage, track };
}

export const CLASSIFY_RULES = { HIGH_ONLY, MIDDLE_OK, REAL_WORLD };
